"""Emit `config/ctm_grid.yaml`, the vertical C transmission grid (ADR 0025).

Axes: total C x maternal transmission b_m x h2 x prevalence K. With C = 0 only
b_m = 0 is run, because b_m scales C and has no effect without it, which gives
4 (C, b_m) cells x 2 h2 x 3 K = 24 scenarios. Seeds run 390001-390024 in
scenario order, so adding a level renumbers the seeds of every later scenario.

Run from the simACE repo root:
    pixi run python scripts/generate_ctm_grid.py
which overwrites `config/ctm_grid.yaml`.
"""

from __future__ import annotations

from pathlib import Path

C_BM_CELLS = [(0.0, 0.0), (0.2, 0.0), (0.2, 0.2), (0.2, 0.5)]
H2_LEVELS = [0.2, 0.5]
K_LEVELS = [0.01, 0.05, 0.15]
FIRST_SEED = 390001

OUTPUT = Path(__file__).resolve().parent.parent / "config" / "ctm_grid.yaml"

HEADER = """\
# Vertical C transmission grid (ADR 0025).
# Generated by scripts/generate_ctm_grid.py. Do not hand-edit: change the axes
# there and rerun it.
#
# Axes: C x b_m x h2 x prevalence K, 24 scenarios.
#   - C 0.2 with b_m (maternal C_transmission) 0, 0.2, 0.5, b_f = 0.
#   - C 0 with b_m 0 only: b_m scales C, so it has no effect when C = 0.
#   - h2 (A) 0.2, 0.5; E = 1 - A - C.
#   - K 0.01, 0.05, 0.15.
# The two traits use the same A, C, E, b_m and K but are drawn independently
# (rA = rC = rE = 0), so the true cross-trait genetic correlation is 0.
# Phenotype: adult/ltm; cases sit above the 1 - K liability quantile and get
# a logistic onset curve centered on cip_x0: trait1 at 30, trait2 at 60,
# with cip_k 0.2.
# Censoring: every phenotyped generation is observed over ages [0, 50]
# (max_age 50, no per-generation windows), with default death censoring.
# N = 1M per generation, G_ped 4 (pedigree keeps the 2 phenotyped
# generations plus their parents and grandparents), G_pheno 2, one replicate.
#
# Names: ctm_C{C}_bm{b_m}_h{h2}_K{K}, values in hundredths.
"""

SCENARIO = """
{name}:
  seed: {seed}
  N: 1000000
  G_ped: 4
  G_pheno: 2
  replicates: 1
  pedigree:
    trait1: {trait}
    trait2: {trait}
  phenotype:
    trait1:
      model: adult
      params: {{ method: ltm, cip_x0: 30, cip_k: 0.2, prevalence: {K} }}
      beta: 1.0
    trait2:
      model: adult
      params: {{ method: ltm, cip_x0: 60, cip_k: 0.2, prevalence: {K} }}
      beta: 1.0
  censoring:
    max_age: 50
    gen_censoring: {{}}
"""


def hundredths(x: float) -> str:
    """Two-digit name code: 0.05 -> '05'."""
    return f"{round(x * 100):02d}"


def render() -> str:
    """Return the full YAML text of the grid."""
    blocks = [HEADER]
    seed = FIRST_SEED
    for C, bm in C_BM_CELLS:
        for A in H2_LEVELS:
            E = round(1 - A - C, 2)
            trait = f"{{ A: {A}, C: {C}, E: {E}, C_transmission: {{ maternal: {bm} }} }}"
            for K in K_LEVELS:
                name = f"ctm_C{hundredths(C)}_bm{hundredths(bm)}_h{hundredths(A)}_K{hundredths(K)}"
                blocks.append(SCENARIO.format(name=name, seed=seed, trait=trait, K=K))
                seed += 1
    return "".join(blocks)


def main() -> None:
    """Write `config/ctm_grid.yaml`."""
    OUTPUT.write_text(render())
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
